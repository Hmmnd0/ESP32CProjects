// Extracts a U8g2 font from u8g2_fonts.c and writes it as a JS glyph table,
// so the web page can draw the exact same tiny font the OLED firmware has.
// Usage: node tools/gen-font.mjs <u8g2_fonts.c> <font_name> <out.js>
import fs from 'node:fs';

const [src, name, out] = process.argv.slice(2);
const text = fs.readFileSync(src, 'latin1');
const start = text.indexOf(`const uint8_t ${name}[`);
if (start < 0) throw new Error('font not found: ' + name);
const size = Number(/\[(\d+)\]/.exec(text.slice(start, start + 200))[1]);

// Concatenate the C string literals and unescape them into bytes, up to the declared size
// (the data itself can contain ';' so we can't just look for the end of the statement)
const bytes = [];
const lits = /"((?:[^"\\]|\\.)*)"/g;
lits.lastIndex = text.indexOf('=', start);
for (let m; bytes.length < size && (m = lits.exec(text));) {
  const s = m[1];
  for (let i = 0; i < s.length; i++) {
    if (s[i] !== '\\') { bytes.push(s.charCodeAt(i)); continue; }
    const m = /^[0-7]{1,3}/.exec(s.slice(i + 1));
    if (m) { bytes.push(parseInt(m[0], 8)); i += m[0].length; continue; }
    const c = s[++i];
    bytes.push({ n: 10, t: 9, r: 13, '\\': 92, '"': 34, "'": 39, '?': 63 }[c] ?? c.charCodeAt(0));
  }
}

const H = {
  bitsPer0: bytes[2], bitsPer1: bytes[3], bitsW: bytes[4], bitsH: bytes[5],
  bitsX: bytes[6], bitsY: bytes[7], bitsDX: bytes[8], ascentA: bytes[13] << 24 >> 24,
};

const glyphs = {};
let p = 23;
while (bytes[p] !== 0 && p < bytes.length) {
  const code = bytes[p], next = bytes[p + 1];
  let bytePos = p + 2, bitPos = 0;
  const bits = (n) => {
    let v = 0;
    for (let i = 0; i < n; i++) {
      v |= ((bytes[bytePos] >> bitPos) & 1) << i;
      if (++bitPos === 8) { bitPos = 0; bytePos++; }
    }
    return v;
  };
  const sbits = (n) => bits(n) - (1 << (n - 1));
  const w = bits(H.bitsW), h = bits(H.bitsH), x = sbits(H.bitsX), y = sbits(H.bitsY), dx = sbits(H.bitsDX);
  const px = [];
  if (w && h) {
    while (px.length < w * h) {
      if (bytePos > p + next) throw new Error('corrupt glyph ' + code);
      const a = bits(H.bitsPer0), b = bits(H.bitsPer1);
      do { for (let i = 0; i < a; i++) px.push(0); for (let i = 0; i < b; i++) px.push(1); } while (bits(1));
    }
  }
  // rows as bitmasks (bit 0 = leftmost pixel)
  const rows = [];
  for (let r = 0; r < h; r++) { let m = 0; for (let c = 0; c < w; c++) if (px[r * w + c]) m |= 1 << c; rows.push(m); }
  glyphs[code] = { w, h, x, y, dx, rows };
  p += next;
}

fs.writeFileSync(out, `// Generated by tools/gen-font.mjs from U8g2 ${name}. Do not edit.\n` +
  `// Each glyph: w/h = bitmap size, x/y = offset from the baseline (y up), dx = advance, rows = bitmasks (bit 0 = left).\n` +
  `export default ${JSON.stringify({ ascent: H.ascentA, glyphs })};\n`);
console.log(`${name}: ${Object.keys(glyphs).length} glyphs, ascent ${H.ascentA}`);
